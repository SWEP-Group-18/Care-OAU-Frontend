const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try {
  const context=await browser.newContext({timezoneId:'Africa/Lagos'});
  const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.clock.install({time:new Date('2026-10-26T09:00:00Z')});
  const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
  await page.goto(base);
  await page.evaluate(()=>localStorage.setItem('care_oau_auth_user',JSON.stringify({id:'staff',name:'Staff Name',staffId:'STAFF/001',role:'admin'})));
  await page.goto(base+'/admin/doctor-management.html');
  await page.selectOption('#status-doc_01','Arriving Soon');
  await page.selectOption('#doctor-arrival','45');
  await page.locator('#confirm-modal-action-btn').click();
  await page.waitForFunction(()=>!document.querySelector('#global-confirm-modal.active'));
  assert.equal(await page.inputValue('#status-doc_01'),'Arriving Soon');
  assert.ok(await page.locator('#status-doc_01').locator('..').innerText().then(t=>t.includes('Expected at')));
  await page.reload();assert.equal(await page.inputValue('#status-doc_01'),'Arriving Soon');
  const student={id:'student',name:'Student Name',matricNo:'CSC/2021/999',email:'student@example.com',phone:'08012345678',isVerified:true,role:'student'};
  await page.evaluate(user=>localStorage.setItem('care_oau_auth_user',JSON.stringify(user)),student);
  await page.goto(base+'/student/doctors.html');
  assert.ok(await page.locator('[data-doctor-id="doc_01"]').innerText().then(t=>t.includes('Arriving Soon')));
  await page.locator('[data-dropdown-toggle]').click();assert.equal(await page.locator('[data-dropdown-toggle]').getAttribute('aria-expanded'),'true');
  await page.getByRole('link',{name:'View Profile',exact:true}).click();await page.waitForURL('**/profile.html');
  assert.ok(await page.locator('#profile-matric').getAttribute('readonly') !== null);
  await page.locator('#edit-profile').click();await page.fill('#profile-name','Changed Name');await page.fill('#profile-email','changed@example.com');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  assert.equal(await page.locator('#profile-display-name').innerText(),'Changed Name');assert.equal(await page.locator('#profile-verification').innerText(),'Not verified');
  await page.reload();assert.equal(await page.inputValue('#profile-name'),'Changed Name');
  await page.locator('#edit-profile').click();await page.fill('#profile-name','Discard This');await page.locator('#cancel-profile').click();assert.equal(await page.inputValue('#profile-name'),'Changed Name');
  await page.fill('#student-password-current','sampleold');await page.fill('#student-password-new','samplenew');await page.fill('#student-password-confirm','different');await page.locator('#student-password-form button').click();assert.ok((await page.locator('#student-password-feedback').innerText()).includes('do not match'));
  await page.fill('#student-password-confirm','samplenew');await page.locator('#student-password-form button').click();assert.ok((await page.locator('#student-password-feedback').innerText()).includes('No password was changed'));
  assert.equal(await page.evaluate(()=>JSON.stringify(localStorage).includes('samplenew')),false);
  for(const width of [1440,768,390]){await page.setViewportSize({width,height:900});await page.waitForTimeout(300);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);}
  const staff = await context.newPage(); staff.on('pageerror', error => errors.push(error.message));
  await staff.route('https://fonts.googleapis.com/**', route => route.abort());
  await staff.clock.install({ time:new Date('2026-10-26T09:00:00Z') });
  await page.goto(base+'/student/doctors.html');
  await staff.goto(base);
  await staff.evaluate(()=>localStorage.setItem('care_oau_auth_user',JSON.stringify({id:'staff',name:'Staff Name',staffId:'STAFF/001',role:'admin'})));
  await staff.goto(base+'/admin/doctor-management.html');
  await staff.selectOption('#status-doc_01','On Leave');
  await page.waitForFunction(()=>document.querySelector('[data-doctor-id="doc_01"]').textContent.includes('On Leave'));
  assert.ok(await page.locator('[data-doctor-id="doc_01"] button').isDisabled());
  await staff.selectOption('#status-doc_01','Available');
  await page.waitForFunction(()=>document.querySelector('[data-doctor-id="doc_01"] .availability-badge').textContent.includes('Available'));
  await staff.locator('[data-dropdown-toggle]').click();await staff.locator('#staff-view-profile').click();
  assert.ok(await staff.locator('#staff-profile-modal').innerText().then(t=>t.includes('STAFF/001')&&t.includes('Clinic administrator')));
  await staff.keyboard.press('Escape');assert.equal(await staff.locator('#staff-profile-modal').evaluate(el=>el.classList.contains('active')),false);
  await staff.locator('[data-dropdown-toggle]').click();await staff.locator('#staff-change-password').click();
  assert.ok(await staff.locator('#staff-password-section').getAttribute('open')!==null);
  await staff.fill('#staff-password-current','sampleold');await staff.fill('#staff-password-new','samplenew');await staff.fill('#staff-password-confirm','samplenew');await staff.locator('#staff-password-form button').click();
  assert.ok((await staff.locator('#staff-password-feedback').innerText()).includes('No password was changed'));
  await staff.setViewportSize({width:390,height:844});await staff.waitForTimeout(300);
  assert.equal(await staff.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await staff.locator('.staff-account-panel').evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await staff.locator('#staff-profile-signout').click();await staff.waitForURL('**/admin/login.html');
  assert.equal(await staff.evaluate(()=>localStorage.getItem('care_oau_auth_user')),null);
  console.log('PASS: cross-tab attendance synchronization, staff profile/password panels, Escape, mobile dialog and sign-out.');
  assert.deepEqual(errors,[]);
  console.log('PASS: staff attendance/arrival persistence, student synchronization, account menu, profile save/cancel, verification reset, demo password validation and responsive widths.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
