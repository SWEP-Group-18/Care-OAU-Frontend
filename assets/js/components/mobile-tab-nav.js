  getCurrentPage() {
    if (typeof window === 'undefined') return '';
    const path = window.location.pathname;
    const file = path.split('/').pop() || 'index.html';
    return file.replace('.html', '');
  },

  render(role = 'student') {
    if (typeof document === 'undefined') return;

    let nav = document.querySelector('.mobile-tab-nav');
    if (!nav) {
      nav = document.createElement('nav');
      nav.className = 'mobile-tab-nav';
      nav.setAttribute('aria-label', `${role === 'admin' ? 'Staff' : 'Student'} Mobile Navigation`);
      document.body.appendChild(nav);
    }

    const tabs = role === 'admin' ? this.getAdminTabs() : this.getStudentTabs();
    const currentPage = this.getCurrentPage();

    nav.innerHTML = tabs.map(tab => {
      const pageKey = tab.href.replace('.html', '');
      const isActive = pageKey === currentPage;
      const activeClass = isActive ? ' active' : '';
      const accentClass = tab.isAccent ? ' mobile-tab-link--accent' : '';

      return `
        <a href="${tab.href}" class="mobile-tab-link${activeClass}${accentClass}" id="${tab.id}" title="${tab.label}" aria-current="${isActive ? 'page' : 'false'}">
          <span class="mobile-tab-icon-wrap">
            ${tab.icon}
          </span>
          <span class="mobile-tab-label">${tab.label}</span>
        </a>
      `;
    }).join('');
  }
